def _compact(value: str, *, limit: int = 4_000) -> str:
    """Return bounded text suitable for context and checkpoint metadata."""

    text = value.strip()
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def _parse_layout_measurement(value: str, *, axis: str) -> float | None:
    """Convert a Markdown image dimension into inches.

    Pandoc accepts several units in image attributes.  Bare values are
    interpreted as CSS pixels, percentages are relative to the content box for
    width or the page for height, and unsupported expressions are left for the
    layout gate to report.
    """

    match = re.fullmatch(r"([0-9]+(?:\.[0-9]+)?)\s*(in|cm|mm|pt|px|%)?", value.strip(), re.I)
    if match is None:
        return None
    amount = float(match.group(1))
    unit = (match.group(2) or "px").casefold()
    if unit == "in":
        return amount
    if unit == "cm":
        return amount / 2.54
    if unit == "mm":
        return amount / 25.4
    if unit == "pt":
        return amount / 72.0
    if unit == "px":
        return amount / 96.0
    page_size = _CONTENT_WIDTH_IN if axis == "width" else _PAGE_HEIGHT_IN
    return page_size * amount / 100.0


def _image_attributes(attributes: str) -> dict[str, str]:
    """Extract simple width/height attributes from a Markdown attribute list."""

    return {
        name.casefold(): value.strip("\"'")
        for name, value in re.findall(r"\b(width|height)\s*=\s*([^\s}]+)", attributes, flags=re.I)
    }


def _jpeg_dimensions(raw: bytes) -> tuple[int, int] | None:
    """Read JPEG dimensions without requiring Pillow."""

    if not raw.startswith(b"\xff\xd8"):
        return None
    index = 2
    while index + 9 < len(raw):
        if raw[index] != 0xFF:
            index += 1
            continue
        while index < len(raw) and raw[index] == 0xFF:
            index += 1
        if index >= len(raw):
            break
        marker = raw[index]
        index += 1
        if marker in (0xD8, 0xD9):
            continue
        if index + 2 > len(raw):
            break
        segment_length = int.from_bytes(raw[index : index + 2], "big")
        if segment_length < 2 or index + segment_length > len(raw):
            break
        if marker in set(range(0xC0, 0xC4)) | set(range(0xC5, 0xC8)) | set(range(0xC9, 0xCC)) | set(
            range(0xCD, 0xD0)
        ):
            if segment_length >= 7:
                height = int.from_bytes(raw[index + 3 : index + 5], "big")
                width = int.from_bytes(raw[index + 5 : index + 7], "big")
                return width, height
        index += segment_length
    return None


def _image_dimensions(path: Path) -> tuple[int, int] | None:
    """Read common raster/vector dimensions for deterministic layout checks."""

    try:
        raw = path.read_bytes()
    except OSError:
        return None
    if raw.startswith(b"\x89PNG\r\n\x1a\n") and len(raw) >= 24:
        return int.from_bytes(raw[16:20], "big"), int.from_bytes(raw[20:24], "big")
    if raw[:6] in (b"GIF87a", b"GIF89a") and len(raw) >= 10:
        return int.from_bytes(raw[6:8], "little"), int.from_bytes(raw[8:10], "little")
    if raw.startswith(b"RIFF") and raw[8:12] == b"WEBP":
        if raw[12:16] == b"VP8X" and len(raw) >= 30:
            width = 1 + int.from_bytes(raw[24:27], "little")
            height = 1 + int.from_bytes(raw[27:30], "little")
            return width, height
        if raw[12:16] == b"VP8 " and len(raw) >= 30 and raw[26:30] == b"\x9d\x01\x2a":
            return int.from_bytes(raw[28:30], "little") & 0x3FFF, int.from_bytes(
                raw[26:28], "little"
            ) & 0x3FFF
    if raw.startswith(b"<") or b"<svg" in raw[:512].lower():
        text = raw[:16_384].decode("utf-8", errors="ignore")
        viewbox = re.search(
            r"\bviewBox\s*=\s*[\"']\s*[-+0-9.eE]+\s+[-+0-9.eE]+\s+([0-9.eE+-]+)\s+([0-9.eE+-]+)",
            text,
        )
        width_match = re.search(r"\bwidth\s*=\s*[\"']\s*([0-9.eE+-]+)", text)
        height_match = re.search(r"\bheight\s*=\s*[\"']\s*([0-9.eE+-]+)", text)
        if viewbox is not None:
            return max(1, round(float(viewbox.group(1)))), max(1, round(float(viewbox.group(2))))
        if width_match is not None and height_match is not None:
            return max(1, round(float(width_match.group(1)))), max(
                1, round(float(height_match.group(1)))
            )
    return _jpeg_dimensions(raw)


def _split_table_row(line: str) -> list[str]:
    """Split a pipe-table row while accepting escaped pipes in cells."""

    row = line.strip()
    if row.startswith("|"):
        row = row[1:]
    if row.endswith("|") and not row.endswith("\\|"):
        row = row[:-1]
    return [cell.replace("\\|", "|").strip() for cell in re.split(r"(?<!\\)\|", row)]


def _is_table_separator(line: str) -> bool:
    """Return whether *line* is the Markdown separator row of a pipe table."""

    cells = _split_table_row(line)
    return len(cells) >= 2 and all(bool(re.fullmatch(r":?-{3,}:?", cell)) for cell in cells)


def _table_layout_issues(path: Path, text: str) -> tuple[int, list[str]]:
    """Estimate table dimensions and return violations for one Markdown file."""

    lines = text.splitlines()
    in_fence = False
    table_count = 0
    issues: list[str] = []
    index = 0
    while index < len(lines):
        line = lines[index]
        if line.strip().startswith("```") or line.strip().startswith("~~~"):
            in_fence = not in_fence
            index += 1
            continue
        if in_fence or index == 0 or not _is_table_separator(line):
            index += 1
            continue
        header = lines[index - 1]
        if "|" not in header:
            index += 1
            continue
        rows = [_split_table_row(header)]
        cursor = index + 1
        while cursor < len(lines) and lines[cursor].strip() and "|" in lines[cursor]:
            rows.append(_split_table_row(lines[cursor]))
            cursor += 1
        table_count += 1
        columns = max(len(row) for row in rows)
        widths = [0] * columns
        for row in rows:
            for column, cell in enumerate(row):
                widths[column] = max(widths[column], len(cell))
        estimated_width = sum(widths) * _TABLE_CELL_CHAR_WIDTH_IN + columns * _TABLE_CELL_PADDING_IN
        estimated_height = len(rows) * _TABLE_ROW_HEIGHT_IN
        label = f"{path.name} table {table_count}"
        if estimated_width > _MAX_TABLE_WIDTH_IN:
            issues.append(
                f"{label} is approximately {estimated_width:.2f}in wide; keep it <= {_MAX_TABLE_WIDTH_IN:.1f}in."
            )
        if estimated_height > _MAX_TABLE_HEIGHT_IN:
            issues.append(
                f"{label} is approximately {estimated_height:.2f}in tall; keep it <= {_MAX_TABLE_HEIGHT_IN:.1f}in (70% of page height)."
            )
        index = cursor
    return table_count, issues


def _layout_image_issues(path: Path, attributes: str) -> list[str]:
    """Check one referenced image against the paperback media bounds."""

    dimensions = _image_dimensions(path)
    attrs = _image_attributes(attributes)
    width = _parse_layout_measurement(attrs["width"], axis="width") if "width" in attrs else None
    height = (
        _parse_layout_measurement(attrs["height"], axis="height") if "height" in attrs else None
    )
    if ("width" in attrs and width is None) or ("height" in attrs and height is None):
        return [
            f"{path.name} uses an unsupported width/height expression; use in, cm, mm, pt, px, or %."
        ]
    if dimensions is None and (width is None or height is None):
        return [
            f"{path.name} has no readable dimensions; add explicit width and height attributes."
        ]
    if dimensions is not None:
        intrinsic_width, intrinsic_height = dimensions
        ratio = intrinsic_height / intrinsic_width if intrinsic_width else 0.0
        if width is None and height is not None:
            width = height / ratio if ratio else None
        elif height is None and width is not None:
            height = width * ratio
    issues: list[str] = []
    if width is not None and width > _TARGET_MEDIA_WIDTH_IN + 1e-6:
        issues.append(
            f"{path.name} is {width:.2f}in wide; keep it <= {_TARGET_MEDIA_WIDTH_IN:.3f}in "
            f"(95% of {_CONTENT_WIDTH_IN:.2f}in content width)."
        )
    if height is not None and height > _MAX_MEDIA_HEIGHT_IN + 1e-6:
        issues.append(
            f"{path.name} is {height:.2f}in tall; keep it <= {_MAX_MEDIA_HEIGHT_IN:.1f}in (70% of page height)."
        )
    return issues


def _layout_findings(output_dir: str, assets_dir: str) -> tuple[list[str], int, int, list[str]]:
    """Scan book sources and return files, media/table counts, and violations."""

    root = Path(output_dir).expanduser().resolve()
    assets_root = Path(assets_dir).expanduser().resolve()
    sources = _files_under(root / "chapters", frozenset({".md"}))
    for directory in (root / "front-matter", root / "back-matter"):
        sources.extend(_files_under(directory, frozenset({".md"})))
    sources = sorted(sources, key=lambda item: str(item))
    issues: list[str] = []
    image_count = 0
    table_count = 0
    if not sources:
        issues.append(
            "no Markdown book sources exist under chapters/ or front/back matter directories"
        )
    for source in sources:
        if source.name.casefold() == "contents.md":
            issues.append(
                f"{source.name} is an agent-authored TOC source; build_book.py generates the TOC."
            )
        try:
            text = source.read_text(encoding="utf-8", errors="replace")
        except OSError as exc:
            issues.append(f"{source.name} could not be read: {exc}")
            continue
        for match in re.finditer(
            r"!\[[^\]]*\]\((?P<target><[^>]+>|[^)\s]+)(?:\s+\"[^\"]*\")?\)(?:\{(?P<attributes>[^}]*)\})?",
            text,
        ):
            target = match.group("target").strip("<>").split("#", 1)[0]
            try:
                candidate = (
                    Path(target) if Path(target).is_absolute() else source.parent / target
                ).resolve(strict=False)
                candidate.relative_to(root)
                candidate.relative_to(assets_root)
            except (ValueError, OSError):
                issues.append(
                    f"{source.name} references an image outside the configured assets directory: {target}"
                )
                continue
            if not candidate.is_file():
                issues.append(f"{source.name} references missing image: {target}")
                continue
            if candidate.suffix.casefold() not in _IMAGE_SUFFIXES:
                issues.append(f"{source.name} references unsupported image format: {target}")
                continue
            image_count += 1
            issues.extend(_layout_image_issues(candidate, match.group("attributes") or ""))
        found_tables, table_issues = _table_layout_issues(source, text)
        table_count += found_tables
        issues.extend(table_issues)
    return _display_paths(sources, str(root)), image_count, table_count, issues


def _path_error(path: str, root: Path, reason: str) -> dict[str, object]:
    """Build a compact artifact error without echoing file contents."""

    return {
        "ok": False,
        "error": f"artifact '{path}' {reason} under '{root}'.",
        "fix": "Create the artifact in the directory named by the phase prompt, then retry the short completion call.",
    }


def _resolve_under(root_text: str, candidate: str, *, kind: str = "file") -> Path:
    """Resolve an untrusted artifact path and reject traversal/symlink escapes."""

    if not root_text.strip():
        raise ValueError("the workflow output directory is not configured")
    if "\x00" in candidate:
        raise ValueError("path contains a NUL character")
    root = Path(root_text).expanduser().resolve()
    raw = Path(candidate).expanduser()
    target = (raw if raw.is_absolute() else root / raw).resolve(strict=False)
    try:
        target.relative_to(root)
    except ValueError as exc:
        raise ValueError("path escapes the configured output directory") from exc
    if kind == "file" and not target.is_file():
        raise FileNotFoundError(str(target))
    if kind == "directory" and not target.is_dir():
        raise FileNotFoundError(str(target))
    return target


def _display_paths(paths: list[Path], root_text: str) -> list[str]:
    """Return deterministic paths relative to the book output root."""

    root = Path(root_text).expanduser().resolve()
    return [str(path.relative_to(root)) for path in sorted(paths, key=lambda item: str(item))]


def _files_under(directory: Path, suffixes: frozenset[str]) -> list[Path]:
    """List regular files in a canonical directory, deterministically."""

    if not directory.is_dir():
        return []
    root = directory.resolve()
    files: list[Path] = []
    for path in directory.rglob("*"):
        if not path.is_file() or path.suffix.lower() not in suffixes:
            continue
        resolved = path.resolve()
        try:
            resolved.relative_to(root)
        except ValueError:
            # A symlinked artifact outside the configured root is not part of
            # the inventory and must never be recorded as a valid handoff.
            continue
        files.append(resolved)
    return sorted(
        files,
        key=lambda path: str(path),
    )


def _chapter_slug(title: str) -> str:
    """Create the chapter filename slug used by the canonical phase prompt."""

    slug = re.sub(r"[^a-z0-9]+", "-", title.casefold()).strip("-")
    return slug or "chapter"


def _canonical_chapter_path(output_dir: str, chapter_index: int, title: str) -> Path:
    """Return the runner-owned default path for a chapter."""

    root = Path(output_dir).expanduser().resolve()
    return root / "chapters" / f"{chapter_index + 1:02d}-{_chapter_slug(title)}.md"


def _toc_manifest_path(run_id: str) -> str:
    """Return the deterministic, run-scoped path for the agent's TOC JSON."""

    safe_id = re.sub(r"[^A-Za-z0-9_.-]+", "-", run_id).strip(".-") or "run"
    return str((Path.cwd() / ".agenthicc" / "make_book" / safe_id / "toc.json").resolve())


def _markdown_asset_references(path: Path, output_dir: str, assets_dir: str) -> list[str]:
    """Extract and verify Markdown image references for one chapter."""

    text = path.read_text(encoding="utf-8", errors="replace")
    references = re.findall(r"!\[[^\]]*\]\(([^)\s]+)", text)
    if not references:
        return []
    assets_root = Path(assets_dir).expanduser().resolve()
    result: list[Path] = []
    for reference in references:
        candidate = reference.split("#", 1)[0].strip().strip("<>")
        if not candidate:
            continue
        try:
            output_root = Path(output_dir).expanduser().resolve()
            raw_reference = Path(candidate).expanduser()
            resolved = (
                raw_reference if raw_reference.is_absolute() else path.parent / raw_reference
            ).resolve(strict=False)
            resolved.relative_to(output_root)
            if not resolved.is_file():
                raise FileNotFoundError(str(resolved))
            resolved.relative_to(assets_root)
        except (ValueError, FileNotFoundError) as exc:
            raise ValueError(
                f"referenced asset '{candidate}' is missing or outside the assets directory"
            ) from exc
        if resolved not in result:
            result.append(resolved)
    return sorted(result, key=lambda item: str(item))


def _unsplash_manifest_entries(value: object) -> list[dict[str, object]]:
    """Normalize the supported Unsplash manifest shapes for validation."""

    if isinstance(value, list):
        return [entry for entry in value if isinstance(entry, dict)]
    if not isinstance(value, dict):
        return []
    for key in ("images", "assets", "entries"):
        nested = value.get(key)
        if isinstance(nested, list):
            return [entry for entry in nested if isinstance(entry, dict)]
    return [value]


